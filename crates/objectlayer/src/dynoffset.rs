/// The position of `v` in a descriptor table, else `default`.
#[inline]
fn scan(table: &[u32], v: u32, default: u32) -> u32 {
    for (i, &t) in table.iter().enumerate() {
        if t == v {
            return i as u32;
        }
    }
    default
}

/// The player getter `0x47d560`: the position of `v` in `PLAYER_A`; if absent and the object is the
/// active player, its position in `PLAYER_B` plus `0x127`; else `0x446`.
#[inline]
fn scan_player(v: u32, self_player: bool) -> u32 {
    for (i, &t) in PLAYER_A.iter().enumerate() {
        if t == v {
            return i as u32;
        }
    }
    if self_player {
        for (i, &t) in PLAYER_B.iter().enumerate() {
            if t == v {
                return i as u32 + 0x127;
            }
        }
    }
    0x446
}

/// `(field_index & 3) + (a + b) * 4`, the closing `lea`, wrapping in 32 bits.
#[inline]
fn combine(field_index: u32, a: u32, b: u32) -> u32 {
    (field_index & 3).wrapping_add(a.wrapping_add(b).wrapping_mul(4))
}

/// `0x466830`: the live-field byte offset of a block id and a field index. `self_player` is the
/// second stack argument and only the player branch reads it; the first stack argument is dead.
pub fn field_dynamic_offset(block_id: u32, field_index: u32, self_player: bool) -> u32 {
    let f = field_index;
    let default_path = || combine(f, scan(&DEFAULT_OBJ, f >> 2, 6), 0);
    match block_id {
        1 if f >= 0x18 => combine(f, scan(&ITEM, (f - 0x18) >> 2, 0x2a), 3),
        2 if f >= 0xc0 => combine(f, scan(&CONTAINER, (f - 0xc0) >> 2, 0x4a), 0x23),
        2 if f >= 0x18 => combine(f, scan(&ITEM, (f - 0x18) >> 2, 0x2a), 3),
        3 if f >= 0x18 => combine(f, scan(&UNIT, (f - 0x18) >> 2, 0xb6), 3),
        4 if f >= 0x2f0 => combine(f, scan_player((f - 0x2f0) >> 2, self_player), 0xaa),
        4 if f >= 0x18 => combine(f, scan(&UNIT, (f - 0x18) >> 2, 0xb6), 3),
        5 if f >= 0x18 => combine(f, scan(&C5, (f - 0x18) >> 2, 0x14), 3),
        6 if f >= 0x18 => combine(f, 10, 3),
        7 if f >= 0x18 => combine(f, scan(&CORPSE, (f - 0x18) >> 2, 0x20), 3),
        _ => default_path(),
    }
}
